#!/usr/bin/env python3
"""Export MVP1 design previews using the existing Go SDUI executable, never parse SDUI here."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile
import xml.etree.ElementTree as ET

BASE = Path(__file__).resolve().parent
SCREENS = (
    ('operator', 'BuckingUI/MainPage.sdui', 'Operator dashboard'),
    ('apt', 'BuckingUI/AptEditor.sdui', 'APT draft editor'),
    ('simulator', 'SimulatorUI/MainPage.sdui', 'Simulator console'),
)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def export(tool, output):
    # Build and validate the entire bundle before publishing files.
    tool = tool.resolve(strict=True)
    with tempfile.TemporaryDirectory(prefix='mvp1-sdui-') as tmp:
        temporary = Path(tmp)
        records = []
        for key, relative, title in SCREENS:
            source = BASE / 'SDL/MVP1/SDUI' / relative
            for fmt, suffix in [('ast', 'ast.json'), ('dump', 'txt'), ('svg', 'svg')]:
                subprocess.run([str(tool), str(source), '--entry', 'page', '--format', fmt,
                                '--width', '1600', '--height', '900', '-o', str(temporary / (key + '.' + suffix))], check=True)
            ast = json.loads((temporary / (key + '.ast.json')).read_text())
            if ast['validation'] != 'local-profile':
                raise ValueError('Export requires validated SDUI profile')
            ET.parse(temporary / (key + '.svg'))
            records.append({'id': key, 'title': title, 'source': 'SDL/MVP1/SDUI/' + relative,
                            'entry': 'page', 'sourceSha256': sha(source.read_bytes())})
        index = ['# MVP1 UI design previews', '',
                 'Generated by export_ui.py through the Go SDUI parser and SVG exporter.',
                 'Static sample states: controls are unbound; no SDL/domain actions are executed.',
                 'These are review snapshots, not on-demand SDL viewpoint generation.', '',
                 '[Source and binding guide](../SDL/MVP1/SDUI/README.md)', '',
                 'Viewport: 1600 x 900 logical units; SDUI source dimensions remain relative.', '']
        for screen in records:
            key = screen['id']
            index += ['## ' + screen['title'], '',
                      '![' + screen['title'] + '](' + key + '.svg)', '',
                      '[SDUI source](../' + screen['source'] + ') | [AST](' + key + '.ast.json) | [Console dump](' + key + '.txt)', '']
        (temporary / 'index.md').write_text('\n'.join(index))
        manifest = {'profile': 'sdui/0.2', 'kind': 'static-design-review', 'viewport': {'width': 1600, 'height': 900},
                    'toolSha256': sha(tool.read_bytes()), 'screens': records,
                    'outputs': {p.name: sha(p.read_bytes()) for p in sorted(temporary.iterdir())}}
        (temporary / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
        output.mkdir(parents=True, exist_ok=True)
        for path in temporary.iterdir():
            target = output / path.name
            # Per-file atomic replacement; this is a local review exporter, not the navigator publication service.
            with tempfile.NamedTemporaryFile(dir=output, delete=False) as stream:
                staged = Path(stream.name)
                stream.write(path.read_bytes())
            try:
                staged.replace(target)
            finally:
                staged.unlink(missing_ok=True)
    print('Exported 3 validated SDUI screens to ' + str(output))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sdui', required=True, type=Path, help='Existing Go SDUI executable')
    parser.add_argument('--output', type=Path, default=BASE / 'preview')
    args = parser.parse_args()
    export(args.sdui, args.output.resolve())
